ALTER TABLE billing_emails DROP CONSTRAINT billing_emails_kind_check;
ALTER TABLE billing_emails ADD CONSTRAINT billing_emails_kind_check
    CHECK (kind IN ('RECEIPT','CANCELLATION','PAYMENT_FAILED','PRICE_CHANGE','IRRELEVANT'));

CREATE TABLE price_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    merchant_key VARCHAR(100) NOT NULL,
    subscription_id BIGINT REFERENCES subscriptions(id) ON DELETE CASCADE,
    billing_email_id BIGINT REFERENCES billing_emails(id) ON DELETE SET NULL,
    source VARCHAR(8) NOT NULL CHECK (source IN ('NOTICE','INVOICE')),
    old_amount NUMERIC(19,4) CHECK (old_amount > 0),
    new_amount NUMERIC(19,4) CHECK (new_amount > 0),
    currency VARCHAR(3),
    effective_on DATE,
    observed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT price_changes_amounts_need_currency CHECK ((old_amount IS NULL AND new_amount IS NULL) OR currency IS NOT NULL)
);
CREATE INDEX idx_price_changes_subscription ON price_changes(subscription_id, observed_at DESC);
CREATE INDEX idx_price_changes_unattached ON price_changes(user_id, merchant_key) WHERE subscription_id IS NULL;

ALTER TABLE subscriptions ADD COLUMN latest_price_change_id BIGINT REFERENCES price_changes(id) ON DELETE SET NULL;
