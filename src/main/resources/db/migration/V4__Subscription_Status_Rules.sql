ALTER TABLE users ADD COLUMN time_zone VARCHAR(64) NOT NULL DEFAULT 'Asia/Tashkent';

ALTER TABLE subscriptions ADD COLUMN status_evidence_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE subscriptions ADD COLUMN ends_on DATE;
CREATE INDEX idx_subscriptions_daily_rules
    ON subscriptions(next_payment_date) WHERE status = 'ACTIVE' AND is_deleted = FALSE;

ALTER TABLE billing_emails ADD COLUMN merchant_key VARCHAR(120);
ALTER TABLE billing_emails ADD COLUMN access_ends_on DATE;
CREATE INDEX idx_billing_emails_unattached
    ON billing_emails(user_id, merchant_key) WHERE subscription_id IS NULL;

CREATE TABLE status_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT NOT NULL REFERENCES subscriptions(id) ON DELETE CASCADE,
    from_status VARCHAR(16) NOT NULL CHECK (from_status IN ('ACTIVE','CANCELLED','BILLING_REQUIRED')),
    to_status VARCHAR(16) NOT NULL CHECK (to_status IN ('ACTIVE','CANCELLED','BILLING_REQUIRED')),
    reason VARCHAR(32) NOT NULL CHECK (reason IN ('EMAIL_RECEIPT','EMAIL_CANCELLATION','CANCELLATION_SCHEDULED',
        'EMAIL_PAYMENT_FAILED','USER','OVERDUE','SCHEDULED_END')),
    billing_email_id BIGINT REFERENCES billing_emails(id) ON DELETE SET NULL,
    effective_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_on DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_status_changes_subscription ON status_changes(subscription_id, effective_at DESC);
