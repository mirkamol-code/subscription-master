ALTER TABLE users ADD COLUMN last_login_at TIMESTAMP WITH TIME ZONE;
CREATE INDEX idx_users_created_at ON users(created_at);
CREATE INDEX idx_users_last_login_at ON users(last_login_at);

CREATE TABLE login_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ip VARCHAR(45),
    user_agent VARCHAR(512)
);
CREATE INDEX idx_login_events_user_occurred ON login_events(user_id, occurred_at DESC);
CREATE INDEX idx_login_events_occurred ON login_events(occurred_at);

CREATE INDEX idx_user_roles_role ON user_roles(role);
ALTER TABLE subscriptions ADD COLUMN merchant_slug VARCHAR(120) GENERATED ALWAYS AS (
    btrim(regexp_replace(lower(coalesce(merchant_key, name)), '[^[:alnum:]]+', '-', 'g'), '-')
) STORED;
CREATE INDEX idx_subscriptions_merchant_slug ON subscriptions(merchant_slug);
