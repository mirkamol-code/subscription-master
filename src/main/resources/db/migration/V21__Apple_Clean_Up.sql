CREATE TABLE apple_clean_up_backups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id UUID NOT NULL,
    user_id BIGINT NOT NULL,
    table_name VARCHAR(40) NOT NULL,
    row_id BIGINT NOT NULL,
    row_data JSONB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_apple_clean_up_backups_user ON apple_clean_up_backups(user_id, run_id);

CREATE TABLE apple_clean_up_attempts (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    missing_email_attempts INTEGER NOT NULL DEFAULT 0 CHECK (missing_email_attempts >= 0),
    last_outcome VARCHAR(32) NOT NULL,
    last_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL
);

