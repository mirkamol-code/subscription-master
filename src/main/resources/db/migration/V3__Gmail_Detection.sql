CREATE TABLE billing_emails (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    subscription_id BIGINT REFERENCES subscriptions(id) ON DELETE SET NULL,
    gmail_message_id VARCHAR(64) NOT NULL,
    thread_id VARCHAR(64),
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('RECEIPT','CANCELLATION','PAYMENT_FAILED','IRRELEVANT')),
    sender VARCHAR(320),
    subject VARCHAR(500),
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    confidence VARCHAR(8) CHECK (confidence IN ('HIGH','LOW')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_billing_emails_user_message UNIQUE (user_id, gmail_message_id)
);
CREATE INDEX idx_billing_emails_subscription ON billing_emails(subscription_id);

CREATE TABLE email_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    billing_email_id BIGINT NOT NULL REFERENCES billing_emails(id) ON DELETE CASCADE,
    gmail_attachment_id TEXT NOT NULL,
    filename VARCHAR(255) NOT NULL,
    mime_type VARCHAR(127) NOT NULL,
    size_bytes BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_email_attachments_email ON email_attachments(billing_email_id);

